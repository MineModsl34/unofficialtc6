    private static SoundEvent register(RegisterEvent.RegisterHelper<SoundEvent> registry, String id) {
        ResourceLocation rl = ResourceLocation.fromNamespaceAndPath(Thaumcraft.MODID, id);
        SoundEvent sound = SoundEvent.createVariableRangeEvent(rl);
        registry.register(rl, sound);
        return sound;
    }
